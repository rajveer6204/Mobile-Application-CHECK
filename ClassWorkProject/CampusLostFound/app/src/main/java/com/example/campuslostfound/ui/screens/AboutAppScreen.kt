            Text(
                text = "Campus Lost & Found",
                fontSize = 22.sp,
                fontWeight = FontWeight.Bold,
                color = TextPrimary
            )

            Text(
                text = "Version 1.0.0 (Build 2024)",
                fontSize = 13.sp,
                fontWeight = FontWeight.SemiBold,
                color = PrimaryPurple
            )

            Spacer(modifier = Modifier.height(24.dp))

            // Mission Statement Card
            Card(
                modifier = Modifier.fillMaxWidth(),
